"""Generate native format metadata from the libgguf-owned registry."""

import argparse
import json
from pathlib import Path


def derivatives(root):
    registry = json.loads((root / "contracts/native_formats.json").read_text())
    formats = registry["formats"]
    if registry["schema_version"] != 1 or [f["id"] for f in formats] != list(range(len(formats))):
        raise ValueError("unsupported native registry schema or noncontiguous IDs")
    enums = "\n".join(f'    {f["name"].split(".")[-1]} = {f["id"]},' for f in formats)
    cases = "\n".join(
        f'    case NativeFormat::{f["name"].split(".")[-1]}: return {{"{f["name"]}", {f["values_per_block"]}, {f["bytes_per_block"]}, {f["values_per_group"]}}};'
        for f in formats
    )
    header = '''// Generated by tools/native_format_registry.py. Edit contracts/native_formats.json.
#pragma once

#include <cstdint>

namespace libgguf {

// These are libgguf-native identifiers, never GGML file type codes.
enum class NativeFormat : std::uint32_t {
ENUMS
};

struct NativeFormatInfo {
    const char* name;
    std::uint32_t values_per_block;
    std::uint32_t bytes_per_block;
    std::uint32_t values_per_group;
};

inline constexpr std::uint32_t native_format_revision = FORMAT_REVISION;
inline constexpr std::uint32_t native_encoder_revision = ENCODER_REVISION;

#if defined(__HIP__) || defined(__HIPCC__)
__attribute__((host, device))
#elif defined(__CUDACC__)
__host__ __device__
#endif
constexpr NativeFormatInfo native_format_info(NativeFormat format) {
    switch (format) {
CASES
    }
    return {nullptr, 0, 0, 0};
}

} // namespace libgguf
'''.replace("ENUMS", enums).replace("CASES", cases).replace("FORMAT_REVISION", str(registry["format_revision"])).replace("ENCODER_REVISION", str(registry["encoder"]["revision"]))
    python = '''"""Generated by tools/native_format_registry.py; IDs are separate from GGML."""

from enum import IntEnum


class NativeQuantizationType(IntEnum):
'''
    python += "\n".join(f'    {f["name"].split(".")[-1].upper()} = {f["id"]}' for f in formats)
    python += f'\n\n\nNATIVE_FORMAT_REVISION = {registry["format_revision"]}\nNATIVE_ENCODER_REVISION = {registry["encoder"]["revision"]}\nNATIVE_QUANT_SIZES = {{\n'
    python += "\n".join(f'    NativeQuantizationType.{f["name"].split(".")[-1].upper()}: ({f["values_per_block"]}, {f["bytes_per_block"]}, {f["values_per_group"]}),' for f in formats)
    python += '''
}
NATIVE_FORMAT_NAMES = {kind: f"libgguf.{kind.name.lower()}" for kind in NativeQuantizationType}


def native_row_size(format: NativeQuantizationType, columns: int) -> int:
    values, size, _ = NATIVE_QUANT_SIZES[NativeQuantizationType(format)]
    if type(columns) is not int or columns <= 0 or columns % values:
        raise ValueError(f"native row width must be a positive multiple of {values}")
    return (columns // values) * size
'''
    return {root / "include/libgguf/common/native_formats.h": header, root / "src/libgguf/native_formats.py": python}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, content in derivatives(root).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(root)))
        else:
            path.write_text(content, newline="\n")
    if stale:
        parser.exit(1, "stale native registry derivatives: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
